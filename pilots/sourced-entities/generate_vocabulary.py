"""Generate the pilot's two language enums from its one versioned vocabulary."""
import argparse
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
_spec = importlib.util.spec_from_file_location("vocabulary_generate", ROOT / "vocabulary/generate.py")
_generate = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_generate)
format_ts = _generate.format_ts  # one formatter for every generated TypeScript file


def generated():
    vocabulary = json.loads((HERE / "vocabulary.json").read_text(encoding="utf-8"))
    groups = {
        "FactType": list(vocabulary["fact_types"]),
        "MentionRole": vocabulary["mention_roles"],
        "RelationshipType": vocabulary["relationship_types"],
        "NameKind": vocabulary["name_kinds"],
        "PilotEventType": vocabulary["event_types"],
    }
    ts = "// Generated by pilots/sourced-entities/generate_vocabulary.py; do not edit.\n"
    ts += f"export const vocabularyVersion = {json.dumps(vocabulary['version'])} as const;\n"
    py = '# Generated by pilots/sourced-entities/generate_vocabulary.py; do not edit.\nfrom typing import Literal\n'
    py += f"VOCABULARY_VERSION = {vocabulary['version']!r}\n"
    for name, values in groups.items():
        ts += f"export const {name[0].lower() + name[1:]}Values = {json.dumps(values)} as const;\n"
        py += f"{name} = Literal[{', '.join(repr(v) for v in values)}]\n"
    return {
        ROOT / "zod/sourced-entities-pilot.vocabulary.ts": format_ts(ts, "sourced-entities-pilot.vocabulary.ts"),
        ROOT / "pydantic/sourced_entities_pilot_vocabulary.py": py,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generated().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"stale generated vocabulary: {path.relative_to(ROOT)}")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
