"""Generate standalone production vocabulary contracts; no package exports yet."""
import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def format_ts(text, name='generated.ts'):
    """Format TypeScript exactly as pruzhany-svelte's `prettier --check src/` expects.

    The site checks the format of every file under its `src/`, which includes this repo's
    `zod/` through a symlink; the version (package.json) and options (.prettierrc) are its own.
    """
    prettier = ROOT / 'node_modules/.bin/prettier'
    if not prettier.exists():
        raise SystemExit('prettier is not installed: run `bun install --frozen-lockfile` first')
    return subprocess.run([str(prettier), '--config', str(ROOT / '.prettierrc'), '--stdin-filepath', name],
                          input=text, capture_output=True, text=True, check=True, cwd=ROOT).stdout


def generated(root=ROOT):
    vocabulary = json.loads((root / 'vocabulary/sourced-entities.json').read_text(encoding='utf-8'))
    ts = '// Generated by vocabulary/generate.py; do not edit.\nimport { z } from \'zod/v4\';\n'
    ts += f'export const vocabularyVersion = {json.dumps(vocabulary["version"])} as const;\n'
    py = '# Generated by vocabulary/generate.py; do not edit.\nfrom typing import Literal, get_args\n'
    py += f'VOCABULARY_VERSION = {vocabulary["version"]!r}\n'
    py += f'VocabularyVersion = Literal[{vocabulary["version"]!r}]\n'
    for group, entries in vocabulary['groups'].items():
        name = ''.join(word.capitalize() for word in group.split('_'))
        values = [entry['id'] for entry in entries]
        ts += f'export const {name}Schema = z.enum({json.dumps(values, ensure_ascii=False)});\n'
        ts += f'export type {name} = z.infer<typeof {name}Schema>;\n'
        py += f'{name} = Literal[{", ".join(repr(v) for v in values)}]\n'
    # The site lists life events only; retained research events and unknown proposals stay out.
    ts += "export const lifeEventKinds = EventTypesSchema.exclude(['other', 'holocaust_event']).options;\n"
    py += "LIFE_EVENT_KINDS = tuple(kind for kind in get_args(EventTypes) if kind not in {'other', 'holocaust_event'})\n"
    kinds = {entry['id']: entry['applies_to'] for entry in vocabulary['groups']['event_parts']}
    ts += f'export const eventPartKinds: Record<EventParts, readonly string[]> = {json.dumps(kinds)};\n'
    py += f'EVENT_PART_KINDS: dict[str, list[str]] = {kinds!r}\n'
    outputs = {root / 'zod/sourced-entities.vocabulary.ts': format_ts(ts, 'sourced-entities.vocabulary.ts'),
               root / 'pydantic/sourced_entities_vocabulary.py': py}
    if vocabulary['status'] == 'released':
        outputs[root / 'vocabulary/released' / (vocabulary['version'] + '.json')] = (
            json.dumps(vocabulary, ensure_ascii=False, indent=2) + '\n')
    outputs.update(generated_site_content(root))
    outputs.update(generated_citation_requirements(root))
    outputs.update(generated_media_rights(root))
    return outputs


def generated_citation_requirements(root=ROOT):
    """Copy the citation table into zod/, which the site reads through a symlink to that folder alone."""
    table = json.loads((root / 'vocabulary/citation-requirements.json').read_text(encoding='utf-8'))
    ts = '// Generated by vocabulary/generate.py from vocabulary/citation-requirements.json; do not edit.\n'
    ts += 'type CitationRequirements = {\n\t[key: string]: unknown;\n\tlanguage_tag_pattern: string;\n\tstatement_types: string[];\n\tkinds: Record<string, unknown>;\n\tprivate_quote_clearance: boolean;\n\tsource_overrides?: Record<string, unknown>;\n};\n'
    ts += f'export const citationRequirements: CitationRequirements = {json.dumps(table, ensure_ascii=False)};\n'
    return {root / 'zod/citation-requirements.table.ts': format_ts(ts, 'citation-requirements.table.ts')}


def generated_site_content(root=ROOT):
    """Keep proposed site terms separate from released production enums."""
    vocabulary = json.loads((root / 'vocabulary/site-content.json').read_text(encoding='utf-8'))
    ts = "// Generated by vocabulary/generate.py; proposed, not released.\nimport { z } from 'zod/v4';\n"
    ts += f'export const siteVocabularyVersion = {vocabulary["version"]!r} as const;\n'
    ts += f'export const siteVocabularyStatus = {vocabulary["status"]!r} as const;\n'
    py = '# Generated by vocabulary/generate.py; proposed, not released.\nfrom typing import Literal\n'
    py += f'SITE_VOCABULARY_VERSION = {vocabulary["version"]!r}\n'
    py += f'SITE_VOCABULARY_STATUS = {vocabulary["status"]!r}\n'
    groups = {'impresso_types': [{'id': value} for value in vocabulary['impresso_types']], **vocabulary['groups']}
    for group, entries in groups.items():
        name = ''.join(word.capitalize() for word in group.split('_'))
        values = [entry['id'] for entry in entries]
        ts += f'export const {name}Schema = z.enum({json.dumps(values)});\n'
        ts += f'export type {name} = z.infer<typeof {name}Schema>;\n'
        py += f'{name} = Literal[{", ".join(repr(v) for v in values)}]\n'
    parents = {entry['id']: entry['parent_type'] for entry in vocabulary['groups']['content_item_subtypes']}
    ts += f'export const subtypeParents = {json.dumps(parents)} as const satisfies Record<ContentItemSubtypes, ImpressoTypes>;\n'
    py += f'SUBTYPE_PARENTS: dict[str, str] = {parents!r}\n'
    return {root / 'zod/site-content.vocabulary.ts': format_ts(ts, 'site-content.vocabulary.ts'),
            root / 'pydantic/site_content_vocabulary.py': py}


def generated_media_rights(root=ROOT):
    """Keep the vendored Zod tree self-contained; standards remains the authored list."""
    rights = json.loads((root / 'standards/media-rights.json').read_text(encoding='utf-8'))
    ts = '// Generated from standards/media-rights.json by vocabulary/generate.py; do not edit.\n'
    ts += f'export const MEDIA_RIGHTS = Object.freeze({json.dumps(rights["uris"])} as const);\n'
    ts += f'export const COPYRIGHT_NOT_EVALUATED = {json.dumps(rights["default"])} as const;\n'
    return {root / 'zod/media-rights.table.ts': format_ts(ts, 'media-rights.table.ts')}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in generated().items():
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode('utf-8'):
                raise SystemExit(f'stale generated vocabulary: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
