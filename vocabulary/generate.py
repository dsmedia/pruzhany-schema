"""Generate standalone production vocabulary contracts; no package exports yet."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated(root=ROOT):
    vocabulary = json.loads((root / 'vocabulary/sourced-entities.json').read_text(encoding='utf-8'))
    ts = '// Generated by vocabulary/generate.py; do not edit.\nimport { z } from \'zod/v4\';\n'
    ts += f'export const vocabularyVersion = {json.dumps(vocabulary["version"])} as const;\n'
    py = '# Generated by vocabulary/generate.py; do not edit.\nfrom typing import Literal\n'
    py += f'VOCABULARY_VERSION = {vocabulary["version"]!r}\n'
    for group, entries in vocabulary['groups'].items():
        name = ''.join(word.capitalize() for word in group.split('_'))
        values = [entry['id'] for entry in entries]
        ts += f'export const {name}Schema = z.enum({json.dumps(values, ensure_ascii=False)});\n'
        ts += f'export type {name} = z.infer<typeof {name}Schema>;\n'
        py += f'{name} = Literal[{", ".join(repr(v) for v in values)}]\n'
    outputs = {root / 'zod/sourced-entities.vocabulary.ts': ts,
               root / 'pydantic/sourced_entities_vocabulary.py': py}
    if vocabulary['status'] == 'released':
        outputs[root / 'vocabulary/released' / (vocabulary['version'] + '.json')] = (
            json.dumps(vocabulary, ensure_ascii=False, indent=2) + '\n')
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in generated().items():
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode('utf-8'):
                raise SystemExit(f'stale generated vocabulary: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
