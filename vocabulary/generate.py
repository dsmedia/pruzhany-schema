def markdown_text(value):
    """Literal source text in a Markdown table cell, including pipes and line breaks."""
    text = html.escape(str(value), quote=False)
    text = re.sub(r'([\\`*_\[\]|])', r'\\\1', text)
    return '<br>'.join(text.splitlines())


def term_link(term, profile):
    """Use the existing namespace expansion; local terms link to their declarations."""
    prefix, name = term.split(':', 1)
    if prefix == 'pc':
        url = f'../vocabulary/{profile}'
    elif prefix == 'skos':
        url = 'http://www.w3.org/2004/02/skos/core#' + name
    else:
        url = NAMESPACES[prefix] + name
    return f'[`{term}`]({url})'


def readable_mapping(entry, profile):
    mapping = entry.get('mapping')
    if mapping is None:
        return 'Not supplied in the JSON.'
    target = meaning(mapping, entry['id'])
    if 'local' in mapping:
        text = f'Local term {term_link(target, profile)}. {markdown_text(mapping["reason"])}'
    else:
        standard = 'RiC-O' if target.startswith('rico:') else 'EHRI'
        text = f'{standard}: {term_link(target, profile)}.'
    if 'via' in mapping:
        text += f' Qualified through {term_link(curie("rico", mapping["via"], entry["id"]), profile)}.'
    if entry.get('concept_class'):
        text += f' Concept type: {term_link(entry["concept_class"], profile)}.'
    if entry.get('rico_parent'):
        text += f' Broader property: {term_link(entry["rico_parent"], profile)}.'
    return text


def readable_table(entries, profile):
    lines = ['| Term and identifier | Definition | Mapping |', '| --- | --- | --- |']
    for entry in entries:
        label = entry.get('label') or entry['id'].replace('_', ' ').capitalize()
        definition = markdown_text(entry.get('definition', 'Not supplied in the JSON.'))
        notes = []
        if entry.get('status'):
            notes.append('Status: ' + markdown_text(entry['status']) + '.')
        if entry.get('deprecated_in'):
            replacement = entry['replaced_by']
            if isinstance(replacement, dict):
                replacement = f'{replacement["group"]}.{replacement["id"]}: {replacement["reason"]}'
            notes.append(f'Deprecated in {markdown_text(entry["deprecated_in"])}; '
                         f'replace with {markdown_text(replacement).rstrip(".")}.')
        if entry.get('parent_type'):
            notes.append(f'Impresso parent type: `{entry["parent_type"]}`.')
        if entry.get('applies_to'):
            notes.append('Used for: ' + ', '.join(f'`{kind}`' for kind in entry['applies_to']) + '.')
        if entry.get('inverse'):
            notes.append(f'Inverse relationship: `{entry["inverse"]}`.')
        if notes:
            definition += '<br>' + ' '.join(notes)
        lines.append(f'| {markdown_text(label)} (`{entry["id"]}`) | {definition} | '
                     f'{readable_mapping(entry, profile)} |')
    return lines


def readable_vocabulary(sources):
    """A data export of the same loaded JSON as the contracts, without release-history copies."""
    unknown = sources.keys() - READABLE_SOURCES.keys()
    if unknown:
        raise SystemExit(f'no readable vocabulary description for: {", ".join(sorted(unknown))}')
    lines = [
        '<!-- Generated by vocabulary/generate.py from vocabulary/*.json; do not edit. -->',
        '# Vocabulary', '',
        'This list explains the terms used to describe the newspaper and its historical evidence. '
        'Each section links to its source JSON. Identifiers in backticks are the values used in the data.', '',
        'Definitions and mappings are reproduced from those files. Where a label is absent, '
        'it is derived from the identifier; missing definitions and mappings are marked explicitly. '
        'A file without a version number is identified as unversioned.', '',
        'EHRI is the European Holocaust Research Infrastructure; RiC-O is the International Council '
        'on Archives’ Records in Contexts Ontology. The [pinned standards](../standards/README.md) '
        'record the versions used. A local term (`pc:`) links to its declaration and gives the '
        'reason for using it. Mappings describe correspondence; they do not turn a disputed or '
        'unreviewed assertion into an established historical fact.', '',
        'Some categories remain for reading older data. Their original definitions are retained; '
        'they do not authorise new conclusions about death or survival from residence alone. '
        'Deprecated terms remain listed with their replacements.', '',
        'See the [released snapshots](../vocabulary/released/) and '
        '[approval history](vocabulary-approvals.md) for earlier versions and decisions. '
        'This generated data page uses [CC BY 4.0](../LICENSE-DATA); see [NOTICE](../NOTICE).', '',
    ]
    for filename, (title, _) in READABLE_SOURCES.items():
        lines.append(f'- [{title}](#{filename.removesuffix(".json")})')
    for filename, (title, purpose) in READABLE_SOURCES.items():
        data = sources[filename]
        profile = 'profile.ttl' if filename == 'sourced-entities.json' else filename.replace('.json', '.profile.ttl')
        lines += ['', f'<a id="{filename.removesuffix(".json")}"></a>', '', f'## {title}', '', purpose, '',
                  f'Source: [{filename}](../vocabulary/{filename}).']
        version = markdown_text(data['version']) if 'version' in data else 'unversioned (no version declared in the JSON)'
        lines += ['', f'Version: {version}.']
        if 'status' in data:
            lines += ['', f'Status: {markdown_text(data["status"])}.']
        if data.get('released_on'):
            lines += ['', f'Release date: {markdown_text(data["released_on"])}.']
        if filename in {'sourced-entities.json', 'site-content.json'}:
            groups = site_content_groups(data) if filename == 'site-content.json' else data['groups']
        elif filename == 'identifiers.json':
            groups = data
        elif filename == 'reading-status.json':
            groups = {'Field and reading states': [{'id': key, **entry} for key, entry in data.items()]}
        else:
            groups = {}
        for group, entries in groups.items():
            lines += ['', f'### {GROUP_TITLES.get(group, group.replace("_", " ").capitalize())}', '']
            lines += readable_table(entries, profile)
        if 'bindings' in data:
            lines += ['', '### Field mappings', '',
                      'These describe how fields correspond to standards; they are not additional controlled values.', '']
            lines += readable_table(data['bindings'], profile)
        if filename == 'citation-requirements.json':
            lines += ['', 'The [source table](../vocabulary/citation-requirements.json) records required '
                      'citation details and alternatives. Proposed source kinds in that table are '
                      'not released vocabulary. Approved source kinds and their definitions appear '
                      'under “Kinds of source” above.']
    return '\n'.join(lines) + '\n'


# A key YAML reads as itself when written bare: a plain identifier that YAML 1.1 does not read as
# a boolean or null. Anything else is written quoted.
PLAIN_KEY = re.compile(r'[A-Za-z_][A-Za-z0-9_]*')
YAML_WORDS = {'true', 'false', 'yes', 'no', 'on', 'off', 'y', 'n', 'null'}


def yaml_scalar(value):
    """A value as JSON, which is a YAML double-quoted scalar or a plain true, false, null or integer.

    A string is quoted whatever it holds, so YAML 1.1 cannot read `on`, `no`, `1.0` or a day as
    anything but text. A character Python counts unprintable is written as an escape too: inside
    quotes YAML folds U+0085, U+2028 and U+2029 into a space, and refuses U+007F.
    """
    if value is None or isinstance(value, (bool, int)):
        return json.dumps(value)
    if not isinstance(value, str):
        raise TypeError(f'no YAML scalar for {type(value).__name__}')
    return ''.join(c if c.isprintable() else
                   (f'\\u{ord(c):04x}' if ord(c) <= 0xFFFF else f'\\U{ord(c):08x}')
                   for c in json.dumps(value, ensure_ascii=False))


def yaml_key(key):
    if not isinstance(key, str):
        raise TypeError(f'a YAML key here is text, not {type(key).__name__}')
    return key if PLAIN_KEY.fullmatch(key) and key.lower() not in YAML_WORDS else yaml_scalar(key)


def yaml_lines(node, depth=0):
    """Block-style YAML: every mapping and list indented, no flow style but an empty {} or []."""
    pad = '  ' * depth
    items = node.items() if isinstance(node, dict) else ((None, item) for item in node)
    for key, value in items:
        head = f'{pad}{yaml_key(key)}:' if isinstance(node, dict) else f'{pad}-'
        if isinstance(value, (dict, list)) and value:
            yield head
            yield from yaml_lines(value, depth + 1)
        elif isinstance(value, (dict, list)):
            yield f'{head} {"{}" if isinstance(value, dict) else "[]"}'
        else:
            yield f'{head} {yaml_scalar(value)}'


def to_yaml(data):
    """The LinkML module as YAML, on the standard library alone (bin/verify's vocabulary step)."""
    header = ('# Generated by vocabulary/generate.py from vocabulary/*.json; do not edit.\n'
              '# Every value is written as JSON, which YAML reads as written.\n')
    return header + '\n'.join(yaml_lines(data)) + '\n'


def generated_media_rights(root=ROOT):
    """Keep the vendored Zod tree self-contained; standards remains the authored list."""
    rights = json.loads((root / 'standards/media-rights.json').read_text(encoding='utf-8'))
    ts = '// Generated from standards/media-rights.json by vocabulary/generate.py; do not edit.\n'
    ts += f'export const MEDIA_RIGHTS = Object.freeze({json.dumps(rights["uris"])} as const);\n'
    ts += f'export const COPYRIGHT_NOT_EVALUATED = {json.dumps(rights["default"])} as const;\n'
    return {root / 'zod/media-rights.table.ts': format_ts(ts, 'media-rights.table.ts')}


def generated_media_widths(root=ROOT):
    """A module, not a JSON import: Node's ESM loader (Playwright) refuses JSON without an attribute."""
    widths = json.loads((root / 'zod/media-widths.json').read_text(encoding='utf-8'))
    wide = json.loads((root / 'zod/media-wide.json').read_text(encoding='utf-8'))
    if set(wide) != {'above', 'width'} or not all(type(v) is int and v > max(widths) for v in wide.values()):
        raise ValueError('zod/media-wide.json needs whole "above" and "width" beyond every listed width')
    if wide['width'] > wide['above']:
        raise ValueError('zod/media-wide.json: a wide copy is never wider than the page it is made from')
    ts = '// Generated from zod/media-widths.json and zod/media-wide.json by vocabulary/generate.py; do not edit.\n'
    ts += f'export const MEDIA_WIDTH_LIST = Object.freeze({json.dumps(widths)} as const);\n'
    ts += f'export const MEDIA_WIDE = Object.freeze({{ above: {wide["above"]}, width: {wide["width"]} }} as const);\n'
    return {root / 'zod/media-widths.table.ts': format_ts(ts, 'media-widths.table.ts')}


def stale(root=ROOT):
    """Each generated file that is missing or differs by a byte from what the generator makes now."""
    return [path for path, content in generated(root).items()
            if not path.exists() or path.read_bytes() != content.encode('utf-8')]


def main(argv=None, root=ROOT):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    if args.check:
        paths = stale(root)
        if paths:
            raise SystemExit('\n'.join(f'stale generated vocabulary: {path.relative_to(root).as_posix()}'
                                       for path in paths))
        return
    for path, content in generated(root).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
